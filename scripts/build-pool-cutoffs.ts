/**
 * Writes src/data/officialPoolCutoffs.json: for each boss cut and board size, the pool spread at
 * OFFICIAL_POOL_PERCENTILE of a large batch of random deals. Official matches are only dealt pools at or
 * under it - see src/lib/officialPool.ts for what that buys and what it does not.
 *
 * Offline and deterministic: the batch is drawn from a fixed PRNG, so rerunning it on the same data
 * files writes the same numbers. Regenerate it whenever the cost table, the prerequisites or either
 * boss set changes - `npm run check` fails until you do (scripts/check-official-pool.ts).
 *
 *   node --experimental-strip-types scripts/build-pool-cutoffs.ts [--samples 20000] [--dry-run]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { buildFlatBoard, dealtPool, type Challenge } from '../src/lib/squareSetFormat.ts'
import { effectiveCosts } from '../src/lib/prereqCost.ts'
import { rng, seedFrom } from '../src/lib/seededRandom.ts'
import { BOARD_SIZES } from '../src/types/battleship.ts'
import { OFFICIAL_POOL_PERCENTILE, POOL_SOURCE_FILES, VETTED_SETS, poolSpread, poolSourceHash } from '../src/lib/officialPool.ts'

const args = process.argv.slice(2)
const DRY_RUN = args.includes('--dry-run')
const SAMPLES = Number(args[args.indexOf('--samples') + 1]) || 20000

const file = (p: string) => readFileSync(new URL(`../src/data/${p}`, import.meta.url), 'utf8')
const texts = POOL_SOURCE_FILES.map(file)
const [bossText, boss2v2Text, costText, prereqText] = texts

const sets: Record<string, Challenge[]> = {
  bosses: JSON.parse(bossText),
  'bosses-2v2': JSON.parse(boss2v2Text),
}
const costT = JSON.parse(costText) as Record<string, number>
const prereqs = JSON.parse(prereqText) as Record<string, unknown>
const costByName: Record<string, number> = {}
for (const set of Object.values(sets)) for (const s of set) if (costT[s.tooltip ?? ''] !== undefined) costByName[s.name] = costT[s.tooltip ?? '']

// The pool a board dealt today draws from - a square not yet live is in no real deal.
const now = new Date().toISOString()

/**
 * One deal's costs, exactly as balance-board's boardCost and official-seed's poolCost build them:
 * same seeding, same pool, same prerequisite discount. A copy, for the reason those two are copies
 * - see the header of balance-board.
 */
function dealCost(setId: string, roomId: string, seed: string, cells: number): number[] {
  const base = setId === 'bosses' ? roomId : `${roomId}:${setId}`
  const board = buildFlatBoard(dealtPool(sets[setId], now), cells, rng(seedFrom(`${base}:${seed}`)))
  const cost = board.map((s) => {
    const c = costT[s.tooltip ?? '']
    if (c === undefined) throw new Error(`no cost for ${s.name}`)
    return c
  })
  return effectiveCosts(board, cost, prereqs, costByName)
}

// Room ids and seeds from a fixed PRNG: a uuid-shaped id and a 9-digit seed, the shapes real rooms
// have, so the hash input looks like the real thing.
const draw = rng(seedFrom('official-pool-cutoffs'))
const hex = (n: number) => Array.from({ length: n }, () => Math.floor(draw() * 16).toString(16)).join('')
const fakeRoom = () => `${hex(8)}-${hex(4)}-4${hex(3)}-${hex(4)}-${hex(12)}`
const fakeSeed = () => String(100_000_000 + Math.floor(draw() * 900_000_000))

const cutoffs: Record<string, Record<string, number>> = {}
const mmss = (s: number) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`
for (const setId of VETTED_SETS) {
  cutoffs[setId] = {}
  const pool = dealtPool(sets[setId], now).length
  for (const size of BOARD_SIZES) {
    const cells = size * size
    if (cells > pool) continue // the set cannot fill this board, so no room can be on it
    const spreads: number[] = []
    for (let i = 0; i < SAMPLES; i++) spreads.push(poolSpread(dealCost(setId, fakeRoom(), fakeSeed(), cells)))
    spreads.sort((a, b) => a - b)
    const cut = spreads[Math.floor(OFFICIAL_POOL_PERCENTILE * (SAMPLES - 1))]
    cutoffs[setId][String(size)] = Math.round(cut * 10) / 10
    console.log(
      `${setId.padEnd(11)} ${String(size).padStart(2)}x${String(size).padEnd(2)}  cutoff ${mmss(cut).padStart(6)}` +
        `   median ${mmss(spreads[Math.floor(SAMPLES / 2)]).padStart(6)}   most even ${mmss(spreads[0]).padStart(6)}`
    )
  }
}

const out = {
  _comment: [
    'GENERATED by scripts/build-pool-cutoffs.ts - do not edit by hand.',
    'Per boss cut and board size: the spread (standard deviation, seconds) of a pool\'s time costs at',
    `\`percentile\` over ${SAMPLES} random deals. Official matches are only dealt pools at or under it.`,
    '`source` fingerprints the data files it was computed from; npm run check fails when they have changed since.',
  ],
  percentile: OFFICIAL_POOL_PERCENTILE,
  samples: SAMPLES,
  source: poolSourceHash(texts),
  cutoffs,
}
if (DRY_RUN) console.log('dry run - nothing written.')
else {
  writeFileSync(new URL('../src/data/officialPoolCutoffs.json', import.meta.url), JSON.stringify(out, null, 2) + '\n')
  console.log('wrote officialPoolCutoffs.json')
}
